"""Makes every chart (PNG) and the markdown result tables from the raw experiment CSV files.

Run from this folder after the Experiments tool:   python make_charts.py
Needs matplotlib. Reads only the CSV files written by com.switchtype.sim.Experiments,
so every number in results_tables.md comes from a measured (simulated) run.
"""
import csv
import os
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
PROFILES = ["quick", "typical", "slow", "tremor", "fatigue"]
LABEL = {"quick": "Quick", "typical": "Typical", "slow": "Slow", "tremor": "Tremor", "fatigue": "Fatigue-prone"}
STYLES = ["LINEAR", "ROW_COLUMN", "GROUP_BINARY"]
LAYOUTS = ["ALPHABETICAL", "QWERTY", "FREQUENCY"]
COLORS = {"LINEAR": "#b45309", "ROW_COLUMN": "#1e40af", "GROUP_BINARY": "#047857",
          "OFF": "#6b7280", "UNIGRAM": "#7c3aed", "BIGRAM": "#1e40af"}


def read(name):
    with open(os.path.join(HERE, name), newline="") as f:
        return list(csv.DictReader(f))


def mean(values):
    values = list(values)
    return sum(values) / len(values) if values else float("nan")


def save(fig, name):
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, name), dpi=110)
    plt.close(fig)
    print("wrote", name)


md = ["# Result tables (generated by make_charts.py from the CSV files)", "",
      "All users are SIMULATED with assumed parameters (profiles.properties). 5 seeds per configuration.", ""]

# ---------------------------------------------------------------- experiment 1
sweep = read("exp1_sweep.csv")
fig, axes = plt.subplots(2, 5, figsize=(20, 7), sharex=True)
for i, p in enumerate(PROFILES):
    for style in STYLES:
        rows = [r for r in sweep if r["profile"] == p and r["style"] == style and r["layout"] == "FREQUENCY"]
        x = [int(r["interval_ms"]) for r in rows]
        axes[0][i].plot(x, [float(r["cpm"]) for r in rows], color=COLORS[style], label=style.replace("_", "-").lower())
        axes[1][i].plot(x, [100 * float(r["total_err"]) for r in rows], color=COLORS[style])
    axes[0][i].set_title(LABEL[p])
    axes[1][i].axhline(5, color="#b91c1c", linestyle="--", linewidth=1)
    axes[1][i].set_xlabel("scan interval (ms)")
axes[0][0].set_ylabel("correct chars / min")
axes[1][0].set_ylabel("total error rate (%)")
axes[0][0].legend(fontsize=8)
fig.suptitle("Experiment 1: speed and errors against scan interval (frequency layout, no prediction)")
save(fig, "exp1_interval_sweep.png")

# ---------------------------------------------------------------- experiment 2
best = read("exp2_best.csv")
md += ["## Experiment 2: best setting per profile (total error rate <= 5 %)", "",
       "| Profile | Style | Layout | Interval (ms) | CPM | WPM | Total error |", "|---|---|---|---|---|---|---|"]
for r in best:
    md.append("| %s | %s | %s | %s | %s | %s | %.1f %% |" % (LABEL[r["profile"]], r["style"], r["layout"],
              r["interval_ms"], r["cpm"], r["wpm"], 100 * float(r["total_err"])))
md.append("")
pareto = read("exp2_pareto.csv")
fig, axes = plt.subplots(1, 5, figsize=(20, 4.2), sharey=False)
for i, p in enumerate(PROFILES):
    rows = [r for r in pareto if r["profile"] == p]
    axes[i].scatter([100 * float(r["total_err"]) for r in rows], [float(r["cpm"]) for r in rows],
                    s=8, color="#9ca3af", label="all settings")
    front = sorted([r for r in rows if r["pareto"] == "1"], key=lambda r: float(r["total_err"]))
    axes[i].plot([100 * float(r["total_err"]) for r in front], [float(r["cpm"]) for r in front],
                 "o-", color="#1e40af", markersize=4, label="Pareto front")
    axes[i].axvline(5, color="#b91c1c", linestyle="--", linewidth=1)
    axes[i].set_xscale("symlog", linthresh=1)
    axes[i].set_title(LABEL[p])
    axes[i].set_xlabel("total error rate (%)")
axes[0].set_ylabel("CPM")
axes[0].legend(fontsize=8)
fig.suptitle("Experiment 2: speed against errors for all 171 settings per profile")
save(fig, "exp2_pareto.png")

# ---------------------------------------------------------------- experiment 3
e3 = read("exp3_styles_layouts.csv")
md += ["## Experiment 3: styles and layouts at each profile's best interval (CPM, total error)", "",
       "| Profile | Interval | " + " | ".join("%s / %s" % (s.split("_")[0].lower(), l[:5].lower())
                                             for s in STYLES for l in LAYOUTS) + " |",
       "|---|---|" + "---|" * 9]
for p in PROFILES:
    rows = {(r["style"], r["layout"]): r for r in e3 if r["profile"] == p}
    cells = ["%.1f (%.0f%%)" % (float(rows[(s, l)]["cpm"]), 100 * float(rows[(s, l)]["total_err"]))
             for s in STYLES for l in LAYOUTS]
    md.append("| %s | %s | %s |" % (LABEL[p], rows[("LINEAR", "FREQUENCY")]["interval_ms"], " | ".join(cells)))
md.append("")
md += ["Presses and scan steps per character (same runs):", "",
       "| Profile | Style | Layout | Presses/char | Steps/char |", "|---|---|---|---|---|"]
for r in e3:
    if r["profile"] == "typical":
        md.append("| %s | %s | %s | %s | %s |" % (LABEL[r["profile"]], r["style"], r["layout"],
                                                 r["presses_per_char"], r["steps_per_char"]))
md.append("")
fig, axes = plt.subplots(1, 5, figsize=(20, 4.2))
for i, p in enumerate(PROFILES):
    rows = {(r["style"], r["layout"]): r for r in e3 if r["profile"] == p}
    for j, s in enumerate(STYLES):
        for k, l in enumerate(LAYOUTS):
            axes[i].bar(j * 4 + k, float(rows[(s, l)]["cpm"]), color=COLORS[s], alpha=0.45 + 0.25 * k)
    axes[i].set_xticks([1, 5, 9])
    axes[i].set_xticklabels(["linear", "row-col", "group-bin"])
    axes[i].set_title("%s (%s ms)" % (LABEL[p], rows[("LINEAR", "FREQUENCY")]["interval_ms"]))
axes[0].set_ylabel("CPM (bars: alphabetical, QWERTY, frequency)")
fig.suptitle("Experiment 3: scan styles and layouts at each profile's best interval")
save(fig, "exp3_styles_layouts.png")

# ---------------------------------------------------------------- experiment 4
e4 = read("exp4_prediction.csv")
md += ["## Experiment 4: word prediction (held-out test phrases)", "",
       "| Profile | Style | Off CPM | Unigram CPM | Bigram CPM | Bigram change | Off presses/char | Bigram presses/char |",
       "|---|---|---|---|---|---|---|---|"]
for p in PROFILES:
    for s in STYLES:
        rows = {r["prediction"]: r for r in e4 if r["profile"] == p and r["style"] == s}
        off, uni, bi = (float(rows[m]["cpm"]) for m in ("OFF", "UNIGRAM", "BIGRAM"))
        md.append("| %s | %s | %.1f | %.1f | %.1f | %+.0f %% | %s | %s |" % (LABEL[p], s, off, uni, bi,
                  100 * (bi - off) / off, rows["OFF"]["presses_per_char"], rows["BIGRAM"]["presses_per_char"]))
md.append("")
ks = read("exp4_keystroke_savings.csv")
md += ["Keystroke savings (perfect user, row-column) and hit rates over %s test words:" % ks[0]["words"], "",
       "| Mode | Selections / char | Keystroke savings | Top-1 / 3 / 5 at word start | Top-1 / 3 / 5 after 1 letter |",
       "|---|---|---|---|---|"]
for r in ks:
    w = float(r["words"])
    md.append("| %s | %.3f | %.1f %% | %.0f / %.0f / %.0f %% | %.0f / %.0f / %.0f %% |" % (
        r["mode"], float(r["selections"]) / float(r["target_chars"]), 100 * float(r["keystroke_savings"]),
        100 * int(r["top1_start"]) / w, 100 * int(r["top3_start"]) / w, 100 * int(r["top5_start"]) / w,
        100 * int(r["top1_after1"]) / w, 100 * int(r["top3_after1"]) / w, 100 * int(r["top5_after1"]) / w))
md.append("")
fig, axes = plt.subplots(1, 3, figsize=(15, 4.2), sharey=True)
for j, s in enumerate(STYLES):
    for k, m in enumerate(["OFF", "UNIGRAM", "BIGRAM"]):
        vals = [float(next(r for r in e4 if r["profile"] == p and r["style"] == s and r["prediction"] == m)["cpm"])
                for p in PROFILES]
        axes[j].bar([i * 4 + k for i in range(5)], vals, color=COLORS[m], label=m.lower())
    axes[j].set_xticks([i * 4 + 1 for i in range(5)])
    axes[j].set_xticklabels([LABEL[p] for p in PROFILES], fontsize=8)
    axes[j].set_title(s.replace("_", "-").lower())
axes[0].set_ylabel("CPM")
axes[0].legend()
fig.suptitle("Experiment 4: prediction off / unigram / bigram at each profile's best interval and layout")
save(fig, "exp4_prediction.png")

# ---------------------------------------------------------------- experiment 5
e5 = read("exp5_adaptive.csv")
md += ["## Experiment 5: adaptive scan speed against fixed intervals (mean of 5 seeds)", "",
       "| Profile | Condition | Start (ms) | CPM | Total error | Median interval, 2nd half (ms) | Time within 20 % of best |",
       "|---|---|---|---|---|---|---|"]
for p in PROFILES:
    groups = defaultdict(list)
    for r in e5:
        if r["profile"] == p:
            groups[r["condition"]].append(r)
    for c, rows in groups.items():
        md.append("| %s | %s | %s | %.1f | %.1f %% | %.0f | %.0f %% |" % (LABEL[p], c, rows[0]["start_ms"],
                  mean(float(r["cpm"]) for r in rows), 100 * mean(float(r["total_err"]) for r in rows),
                  mean(float(r["median_interval_2nd_half"]) for r in rows),
                  100 * mean(float(r["share_time_within_20pct"]) for r in rows)))
md.append("")
trace = read("exp5_trace.csv")
fig, axes = plt.subplots(1, 5, figsize=(20, 4.2), sharey=True)
for i, p in enumerate(PROFILES):
    best_ms = int(next(r for r in best if r["profile"] == p)["interval_ms"])
    for c, color in (("adaptive_from_1000", "#1e40af"), ("adaptive_from_fast", "#b45309"),
                     ("adaptive_from_slow", "#047857")):
        rows = [r for r in trace if r["profile"] == p and r["condition"] == c]
        axes[i].step([float(r["minute"]) for r in rows], [int(r["interval_ms"]) for r in rows], where="post",
                     color=color, label=c.replace("adaptive_", ""))
    axes[i].axhline(best_ms, color="#111827", linestyle="--", linewidth=1, label="best fixed")
    axes[i].set_title(LABEL[p])
    axes[i].set_xlabel("minutes (seed 1)")
axes[0].set_ylabel("scan interval (ms)")
axes[0].legend(fontsize=8)
fig.suptitle("Experiment 5: interval chosen by the adaptive controller over time")
save(fig, "exp5_adaptive_trace.png")

# ---------------------------------------------------------------- experiment 6
e6 = read("exp6_fatigue.csv")
md += ["## Experiment 6: 30-minute sessions with fatigue (mean of 5 seeds)", "",
       "| Profile | Condition | Correct chars in 30 min | CPM over 30 min | CPM first quarter | CPM last quarter | Last / first |",
       "|---|---|---|---|---|---|---|"]
for p in PROFILES:
    for c in ("no_rest", "rest_2min_every_10", "adaptive_no_rest"):
        rows = [r for r in e6 if r["profile"] == p and r["condition"] == c]
        md.append("| %s | %s | %.0f | %.1f | %.1f | %.1f | %.2f |" % (LABEL[p], c,
                  mean(float(r["correct_chars_30min"]) for r in rows), mean(float(r["cpm_30min"]) for r in rows),
                  mean(float(r["cpm_first_quarter"]) for r in rows), mean(float(r["cpm_last_quarter"]) for r in rows),
                  mean(float(r["last_over_first"]) for r in rows)))
md.append("")
tl = read("exp6_timeline.csv")
fig, axes = plt.subplots(1, 5, figsize=(20, 4.2), sharey=False)
for i, p in enumerate(PROFILES):
    for c, color in (("no_rest", "#b91c1c"), ("rest_2min_every_10", "#047857"), ("adaptive_no_rest", "#1e40af")):
        by_minute = defaultdict(list)
        for r in tl:
            if r["profile"] == p and r["condition"] == c:
                by_minute[float(r["minute"])].append(float(r["cpm"]))
        xs = sorted(by_minute)
        axes[i].plot(xs, [mean(by_minute[x]) for x in xs], "o-", color=color, markersize=3, label=c)
    axes[i].set_title(LABEL[p])
    axes[i].set_xlabel("minute of session (3-min bins)")
axes[0].set_ylabel("CPM")
axes[0].legend(fontsize=8)
fig.suptitle("Experiment 6: typing speed over a 30-minute session with fatigue")
save(fig, "exp6_fatigue.png")

# ---------------------------------------------------------------- experiment 7
e7 = read("exp7_sensitivity.csv")
md += ["## Experiment 7: sensitivity of the conclusions (each parameter x0.8 and x1.2, then all)", "",
       "| Profile | Variants | Best style unchanged | Frequency layout still best | Bigram still helps | Adaptive within 10 % of best fixed | Best interval range (ms) |",
       "|---|---|---|---|---|---|---|"]
for p in PROFILES:
    rows = [r for r in e7 if r["profile"] == p and r["best_style"] != "none"]
    base = next(r for r in rows if r["variant"] == "base")
    n = len(rows)
    same_style = sum(r["best_style"] == base["best_style"] for r in rows)
    freq = sum(r["freq_layout_best"] == "1" for r in rows)
    bigram = sum(float(r["bigram_gain_pct"]) > 0 for r in rows)
    adaptive = sum(float(r["adaptive_gap_pct"]) <= 10 for r in rows)
    intervals = [int(r["best_interval"]) for r in rows]
    md.append("| %s | %d | %d / %d (%s) | %d / %d | %d / %d | %d / %d | %d to %d |" % (LABEL[p], n, same_style, n,
              base["best_style"], freq, n, bigram, n, adaptive, n, min(intervals), max(intervals)))
md.append("")
md += ["Variants where the best style changed:", ""]
for r in e7:
    base = next(b for b in e7 if b["profile"] == r["profile"] and b["variant"] == "base")
    if r["best_style"] != base["best_style"]:
        md.append("- %s, %s: %s instead of %s" % (LABEL[r["profile"]], r["variant"], r["best_style"], base["best_style"]))
md.append("")

# ---------------------------------------------------------------- experiment 8
e8 = read("exp8_validation.csv")
md += ["## Experiment 8: model validation", "",
       "| Check | Style | Layout | Analytic steps | Simulated steps | Difference (%) | Analytic presses | Simulated presses |",
       "|---|---|---|---|---|---|---|---|"]
for r in e8:
    if r["check"] == "zero_noise":
        md.append("| zero noise | %s | %s | %s | %s | %s | %s | %s |" % (r["style"], r["layout"], r["a"], r["b"],
                                                                      r["c"], r["d"], r["e"]))
md += ["", "| Sanity check | Interval (ms) | Total error rate | CPM |", "|---|---|---|---|"]
for r in e8:
    if r["check"].startswith("sanity"):
        md.append("| %s | %s | %.1f %% | %s |" % (r["check"].replace("sanity_comp", "compensation "), r["a"],
                                                 100 * float(r["b"]), r["c"]))
for r in e8:
    if r["check"].startswith("seed"):
        md.append("")
        md.append("- %s: CPM %s and %s (%s)" % (r["check"], r["a"], r["b"], r["c"]))
md.append("")

# ---------------------------------------------------------------- experiment 9
if os.path.exists(os.path.join(HERE, "exp9_timing.csv")):
    e9 = read("exp9_timing.csv")
    md += ["## Experiment 9: real-time accuracy of ScannerThread (60 s per row, real clock)", "",
           "| Interval (ms) | Busy threads | Priority | Steps | Mean late (ms) | 99th pct late (ms) | Max late (ms) |",
           "|---|---|---|---|---|---|---|"]
    for r in e9:
        md.append("| %s | %s | %s | %s | %s | %s | %s |" % (r["interval_ms"], r["busy_threads"], r["priority"],
                  r["steps"], r["mean_late_ms"], r["p99_late_ms"], r["max_late_ms"]))
    md.append("")
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.2), sharey=True)
    for j, interval in enumerate(["200", "500", "1000"]):
        rows = [r for r in e9 if r["interval_ms"] == interval]
        labels = ["load %s\nprio %s" % (r["busy_threads"], r["priority"]) for r in rows]
        axes[j].bar(range(len(rows)), [float(r["p99_late_ms"]) for r in rows], color="#1e40af", label="99th percentile")
        axes[j].bar(range(len(rows)), [float(r["mean_late_ms"]) for r in rows], color="#93c5fd", label="mean")
        axes[j].set_xticks(range(len(rows)))
        axes[j].set_xticklabels(labels, fontsize=7)
        axes[j].set_title("interval %s ms" % interval)
    axes[0].set_ylabel("step lateness (ms)")
    axes[0].legend()
    fig.suptitle("Experiment 9: how late the real scanner thread steps (idle and under CPU load)")
    save(fig, "exp9_timing.png")

with open(os.path.join(HERE, "results_tables.md"), "w") as f:
    f.write("\n".join(md) + "\n")
print("wrote results_tables.md")
